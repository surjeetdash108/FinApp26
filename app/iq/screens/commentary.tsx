interface GlanceResponse { generating: boolean; items: GlanceDoc[]; }

/** Sentiment styling for the glance digests — colour, a friendly label, and a
 *  glyph so each period reads at a glance instead of as a wall of grey text. */
const SENT: Record<GlanceSentiment, { color: string; label: string; icon: string }> = {
  bullish: { color: "var(--up)",             label: "Bullish", icon: "📈" },
  bearish: { color: "var(--down)",           label: "Bearish", icon: "📉" },
  mixed:   { color: "var(--warn)",           label: "Mixed",   icon: "🔀" },
  neutral: { color: "var(--text-dim-solid)", label: "Neutral", icon: "➖" },
};

/** Engaging replacement for the plain uppercase-bullet AnnList inside a glance
 *  digest: each item becomes a soft, accent-tinted chip with a colour dot, so
 *  themes / earnings / movers scan as tags rather than a dense list. */
function GlanceChips({ title, icon, items, color }: {
  title: string; icon: string; items?: string[]; color: string;
}) {
  if (!items || items.length === 0) return null;
  return (
    <div>
      <div style={{ display: "flex", alignItems: "center", gap: 7, marginBottom: 9 }}>
        <span aria-hidden style={{ fontSize: ".9rem", lineHeight: 1 }}>{icon}</span>
        <span style={{ fontSize: ".68rem", fontWeight: 700, textTransform: "uppercase", letterSpacing: ".07em", color: "var(--text-dim-solid)" }}>{title}</span>
      </div>
      <div style={{ display: "flex", flexWrap: "wrap", gap: 7 }}>
        {items.map((x, i) => (
          <span key={i} style={{
            display: "inline-flex", alignItems: "center", gap: 8, maxWidth: "100%",
            fontSize: ".78rem", lineHeight: 1.45, color: "var(--text)",
            background: `color-mix(in srgb, ${color} 9%, var(--surface-2))`,
            border: `1px solid color-mix(in srgb, ${color} 24%, var(--border-soft))`,
            borderRadius: 9, padding: "6px 11px",
          }}>
            <span style={{ width: 6, height: 6, borderRadius: "50%", background: color, flexShrink: 0 }} />
            <span>{x}</span>
          </span>
        ))}
      </div>
    </div>
  );
}

/** "August 2026" (monthly) or "Week of Aug 24 – 30, 2026" (weekly). All UTC so
 *  the label matches the period keys the backend wrote. */
function glanceLabel(d: GlanceDoc): string {
  const s = new Date(d.periodStart);
  if (d.period === "monthly") {
    return s.toLocaleDateString(undefined, { month: "long", year: "numeric", timeZone: "UTC" });
  }
  const e = new Date(Date.parse(d.periodEnd) - 24 * 3600 * 1000); // inclusive last day
  const sM = s.toLocaleDateString(undefined, { month: "short", day: "numeric", timeZone: "UTC" });
  const eM = e.toLocaleDateString(undefined, { month: "short", day: "numeric", year: "numeric", timeZone: "UTC" });
  return `Week of ${sM} – ${eM}`;
}

/** One market-wide digest per period, newest first, as an expandable list so
 *  users can open past periods. The current period is generated on demand and
 *  the tab polls until it appears; past periods are read straight from cache. */
function GlanceTab({ period, heading }: { period: "weekly" | "monthly"; heading: string }) {
  // Generation is synchronous server-side: the first view of a stale period
  // waits (~seconds) while `loading` is true, then this returns the full digest.
  const { data, loading } = useApiResource<GlanceResponse>(`/live/glance/${period}`);
  const [openKey, setOpenKey] = useState<string | null>(null); // null = default to first
  const items = data?.items ?? [];
  const openEff = openKey === null ? (items[0]?.periodKey ?? null) : (openKey === "" ? null : openKey);

  return (
    <div style={{ padding: "14px 18px 18px" }}>
      <div className="card">
        <div className="card-h">
          <div style={{ display: "flex", alignItems: "center", gap: 6 }}>
            <h3>{heading}</h3>
            <span style={{ fontSize: ".58rem", fontWeight: 700, letterSpacing: ".04em", padding: "2px 5px", borderRadius: 4, background: "var(--ai)", color: "#fff" }}>AI</span>
          </div>
          <span style={{ fontSize: ".72rem", color: "var(--text-dim-solid)" }}>
            {items.length} {items.length === 1 ? "period" : "periods"}
          </span>
        </div>
        <div className="card-b" style={{ padding: 0, maxHeight: "none" }}>
          {items.length === 0 ? (
            <div style={{ padding: "40px 18px", textAlign: "center" }}>
              <DataState loading={loading}
                label="No summaries yet — a market-wide digest is built from the period's ticker analyses on first view." />
            </div>
          ) : items.map((it) => {
            const isOpen = it.periodKey === openEff;
            const isCurrent = Date.parse(it.periodEnd) > Date.now();
            const noContent = !it.marketTone && it.keyThemes.length === 0 && it.notableMovers.length === 0;
            const sc = SENT[it.sentiment];
            return (
              <div key={it.periodKey} style={{
                borderBottom: "1px solid var(--border-soft)",
                // Soft sentiment-tinted left rail + wash, brighter when the
                // period is open so the eye lands on the expanded digest.
                borderLeft: `3px solid ${isOpen ? sc.color : "transparent"}`,
                background: isOpen ? `color-mix(in srgb, ${sc.color} 5%, transparent)` : "transparent",
                transition: "background .18s ease, border-color .18s ease",
              }}>
                <button
                  onClick={() => setOpenKey(isOpen ? "" : it.periodKey)}
                  style={{ width: "100%", display: "flex", alignItems: "center", gap: 12, padding: "12px 14px", background: "none", border: 0, cursor: "pointer", textAlign: "left", color: "inherit" }}>
                  {/* Sentiment glyph in a soft tinted tile — an at-a-glance mood
                      cue so each period leads with colour, not grey text. */}
                  <span aria-hidden style={{
                    width: 34, height: 34, flexShrink: 0, display: "grid", placeItems: "center",
                    fontSize: "1rem", borderRadius: 10,
                    background: `color-mix(in srgb, ${sc.color} 15%, var(--surface-2))`,
                    border: `1px solid color-mix(in srgb, ${sc.color} 28%, var(--border-soft))`,
                  }}>{sc.icon}</span>
                  <div style={{ minWidth: 0, flex: 1 }}>
                    {/* Deliberately NOT .tkr. That class is the fixed-width
                        ticker-symbol style — `width: 52px` with
                        `.tkr small { display: block }` — which is right for
                        "NVDA" and wrong for a date range: it boxed
                        "Week of Aug 24 – Aug 30, 2026" into 52px and pushed
                        "· current" onto its own line. Plain styles here, with
                        nowrap so the range never splits at its en dash. */}
                    <span style={{
                      display: "block", fontSize: ".84rem", fontWeight: 700, color: "var(--text-hi)",
                      whiteSpace: "nowrap", overflow: "hidden", textOverflow: "ellipsis",
                    }}>
                      {glanceLabel(it)}
                      {isCurrent && (
                        <small style={{
                          marginLeft: 7, fontSize: ".58rem", fontWeight: 700, letterSpacing: ".05em",
                          textTransform: "uppercase", color: "var(--up)", verticalAlign: "middle",
                          background: "color-mix(in srgb, var(--up) 15%, transparent)",
                          borderRadius: 5, padding: "2px 6px",
                        }}>● Live</small>
                      )}
                    </span>
                    <div style={{ fontSize: ".76rem", color: "var(--text-dim-solid)", lineHeight: 1.4, overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap", marginTop: 1 }}>
                      {it.marketTone || it.summary}
                    </div>
                  </div>
                  {!noContent && (
                    <span style={{
                      flexShrink: 0, display: "inline-flex", alignItems: "center", gap: 6,
                      fontSize: ".7rem", fontWeight: 700, color: sc.color, borderRadius: 20, padding: "4px 11px",
                      background: `color-mix(in srgb, ${sc.color} 13%, transparent)`,
                      border: `1px solid color-mix(in srgb, ${sc.color} 30%, transparent)`,
                    }}>
                      <span style={{ width: 6, height: 6, borderRadius: "50%", background: sc.color }} />
                      {sc.label}
                    </span>
                  )}
                  <span style={{ fontSize: ".7rem", color: "var(--text-dim-solid)", flexShrink: 0 }}>{isOpen ? "▲" : "▼"}</span>
                </button>
                {isOpen && (
                  <div style={{ padding: "4px 16px 18px 16px", display: "flex", flexDirection: "column", gap: 16 }}>
                    {/* Market tone as a lead line with a sentiment-coloured rail —
                        the headline read, not just another paragraph. */}
                    {it.marketTone && (
                      <p style={{
                        margin: 0, fontSize: ".92rem", lineHeight: 1.55, fontWeight: 600, color: "var(--text-hi)",
                        borderLeft: `3px solid ${sc.color}`, paddingLeft: 13,
                      }}>{it.marketTone}</p>
                    )}
                    {it.summary && <p style={{ fontSize: ".83rem", lineHeight: 1.6, margin: 0, color: "var(--text)" }}>{it.summary}</p>}
                    <GlanceChips title="Key themes"       icon="🎯" items={it.keyThemes}       color="var(--brand)" />
                    <GlanceChips title="Biggest earnings" icon="📊" items={it.biggestEarnings} color="var(--ai)" />
                    <GlanceChips title="Notable movers"   icon="🚀" items={it.notableMovers}   color={sc.color} />
                    <div style={{ fontSize: ".64rem", color: "var(--text-dim-solid)", display: "flex", alignItems: "center", gap: 7, flexWrap: "wrap", paddingTop: 10, borderTop: "1px solid var(--border-soft)" }}>
                      <span style={{ fontSize: ".55rem", fontWeight: 700, letterSpacing: ".04em", padding: "1px 5px", borderRadius: 4, background: "var(--ai)", color: "#fff" }}>AI</span>
                      Not investment advice · {it.sourceCount} {it.sourceCount === 1 ? "analysis" : "analyses"}
                      {it.generatedAt ? ` · generated ${String(it.generatedAt).slice(0, 16).replace("T", " ")}` : ""}
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}

export function CommentaryScreen() {
  const router = useRouter();
  const uid = firebaseAuth.currentUser?.uid ?? null;
  const { data: liveNews, loading: liveNewsLoading } = useApiList<NewsArticleDoc>("/market-data/news");
  const { data: companies, loading: companiesLoading } = useApiList<CompanyDoc>("/market-data/companies");
  // /market-data/filings-wire and /market-data/macro-regime were fetched here
  // only to fill the Filings wire and Market regime rail cards. With the rail
  // gone nothing on this screen reads them, so the two requests go too rather
  // than loading data that is never rendered. The macro-regime read still has a
  // home on the Macro & VIX screen.
  const [mainTab,       setMainTab]       = useState(0); // 0 = News, 1 = Announcement
  const [activeTab,     setActiveTab]     = useState(0);
  const [search,        setSearch]        = useState("");
  const [secFilter,     setSecFilter]     = useState("All");
  const [capFilter,     setCapFilter]     = useState("All");
  const [tagFilter,     setTagFilter]     = useState<string>("all");
  /* Default ON: ~26% of the feed is auto-generated 13F notes and listicles,
     mostly from defenseworld.net and Motley Fool syndication. */
  // The "Hide filler" toggle is gone: it defaulted ON and silently dropped
  // items tagged `filler` (auto-generated 13F notes, ranked-list clickbait),
  // so the feed never showed everything the backend had. Every item now
  // renders and the reader decides. `filler` is still written by the news job
  // and stays on NewsArticleDoc for anything that wants it later.
  /* Which ticker's rolling AI analysis is open. Read-only: the endpoint never
     triggers generation, so opening this cannot incur a model call. */
  const [analysisTicker, setAnalysisTicker] = useState<string | null>(null);
  const searchRef = useRef<HTMLInputElement>(null);

  const companyByTicker = new Map(companies.map(c => [c.ticker, c]));

  const [mySymbols, setMySymbols] = useState<Set<string>>(new Set());
  useEffect(() => {
    (async () => {
      if (!uid) return new Set<string>();
      const [w, p] = await Promise.all([
        apiGet<WatchlistDoc>("/api/watchlist").catch(() => ({ tickers: [] as string[] })),
        apiGet<{ holdings: HoldingDoc[] }>("/api/portfolio").catch(() => ({ holdings: [] as HoldingDoc[] })),
      ]);
      return new Set([...w.tickers, ...p.holdings.map(h => h.ticker)]);
    })().then(setMySymbols);
  }, [uid]);

  const symbolList = [...companies].filter(c => !!c.ticker).sort((a, b) => (b.marketCap ?? 0) - (a.marketCap ?? 0)).map(c => ({ s: c.ticker, n: c.name ?? c.ticker }));
  const topSymbols = symbolList.slice(0, 8).map(x => x.s);
  /* Plain free-text search — matches anywhere in the message (ticker / headline / summary). */
  const q = search.trim().toLowerCase();

  const sorted = [...liveNews].sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime());
  const premarket  = sorted.filter(n => etHour(n.publishedAt) < 9.5);
  const afterHours = sorted.filter(n => etHour(n.publishedAt) >= 16);
  const macro      = sorted.filter(n => n.category !== "company");
  const myFeed     = sorted.filter(n => mySymbols.has(n.ticker));

  const tabFeed: NewsArticleDoc[] = (() => {
    if (activeTab === 1) return premarket;
    if (activeTab === 2) return afterHours;
    if (activeTab === 3) return myFeed;
    if (activeTab === 4) return macro;
    return sorted;
  })();

  // Sector dropdown uses the SAME unified option set as every other screen —
  // "All" + live GICS sectors + curated theme baskets — so filtering the feed
  // by company.sector (or by theme ticker membership) is uniform app-wide.
  const feedSectors = sectorFilterOptions(companies);
  const effSec = feedSectors.includes(secFilter) ? secFilter : "All";

  /* Filter the feed by the typed text + sector + market-cap (on top of the tab).
     Sector/cap are resolved from the companies doc for each item's ticker; an
     item whose ticker isn't in the companies collection is excluded once either
     of those filters is active (it can't be classified). */
  const displayFeed = tabFeed.filter(n => {
    if (q &&
      !((n.ticker ?? "").toLowerCase().includes(q) ||
        (n.headline ?? "").toLowerCase().includes(q) ||
        (n.summary ?? "").toLowerCase().includes(q))) return false;
    if (tagFilter !== "all" && (n.tag ?? "other") !== tagFilter) return false;
    if (effSec !== "All" || capFilter !== "All") {
      const c = companyByTicker.get(n.ticker);
      if (effSec !== "All" && !matchesSector(effSec, n.ticker, c?.sector)) return false;
      if (capFilter !== "All" && capTier(c?.marketCap) !== capFilter) return false;
    }
    return true;
  });

  /* Chip counts come from the feed BEFORE the tag filter is applied, so the
     numbers stay put when you select a chip — a count that collapsed to its
     own bucket the moment you clicked it would be useless for comparison. */
  const tagCounts = (() => {
    const base = tabFeed.filter(n => {
      if (q &&
        !((n.ticker ?? "").toLowerCase().includes(q) ||
          (n.headline ?? "").toLowerCase().includes(q) ||
          (n.summary ?? "").toLowerCase().includes(q))) return false;
      if (effSec !== "All" || capFilter !== "All") {
        const c = companyByTicker.get(n.ticker);
        if (effSec !== "All" && !matchesSector(effSec, n.ticker, c?.sector)) return false;
        if (capFilter !== "All" && capTier(c?.marketCap) !== capFilter) return false;
      }
      return true;
    });
    const counts: Record<string, number> = { all: base.length };
    for (const n of base) {
      const t = n.tag ?? "other";
      counts[t] = (counts[t] ?? 0) + 1;
    }
    return counts;
  })();

  /* Collapse multi-ticker duplicates. Polygon tags one article to EVERY ticker
     it mentions, so the same story arrives once per ticker (an Alphabet piece
     gets tagged both GOOG and MSFT). In this aggregated feed we show it ONCE,
     keeping the ticker whose company name actually appears in the headline
     (so the Alphabet story keeps GOOG, not the incidental MSFT mention). */
  const feed = (() => {
    const byKey = new Map<string, NewsArticleDoc>();
    const order: string[] = [];
    const relevance = (n: NewsArticleDoc) => {
      const nm = companyByTicker.get(n.ticker)?.name?.split(/[\s,.]/)[0]?.toLowerCase();
      return nm && nm.length > 2 && (n.headline ?? "").toLowerCase().includes(nm) ? 1 : 0;
    };
    for (const n of displayFeed) {
      const key = n.url || n.id;
      const cur = byKey.get(key);
      if (!cur) { byKey.set(key, n); order.push(key); }
      else if (relevance(n) > relevance(cur)) byKey.set(key, n);
    }
    return order.map(k => byKey.get(k) as NewsArticleDoc);
  })();

  // LIVE %change for the tickers actually rendered in the feed, via the app-wide
  // shared poll — one timer for the whole app, so a story's %change here matches
  // the same ticker on the heatmap, movers and the stock drawer exactly.
  const feedQuotes = useLiveQuotes(feed.map(n => n.ticker).filter(Boolean));

  const feedLabel = (() => {
    if (activeTab === 0) return { title: "Intraday commentary", badge: <span className="live"><span className="dot" />Live · streaming</span> };
    if (activeTab === 1) return { title: "Pre-market · before 9:30a ET", badge: <span className="pill" style={{ background: "var(--surface-3)", color: "var(--brand-2)" }}>Pre-market</span> };
    if (activeTab === 2) return { title: "After hours · post 4:00p ET", badge: <span className="pill amc">After hours</span> };
    if (activeTab === 3) return { title: `My names · ${mySymbols.size} tracked`, badge: <span className="pill ai">Portfolio + Watchlist</span> };
    if (activeTab === 4) return { title: "Macro & rates", badge: <span className="pill" style={{ background: "var(--surface-3)", color: "var(--warn)" }}>Macro</span> };
    return { title: "Commentary", badge: null };
  })();


  return (
    <>
      {/* Primary tabs: News vs Earnings Announcement. Everything that used to be
          the Live Feed lives under News; Earnings Announcement will surface the
          per-ticker `announcement`-type AI reads (ticker_ai_analysis, generated
          when an earnings result lands). Placeholder until that's wired. */}
      <div className="page-head">
        <div className="tabs">
          <button className={`tab${mainTab === 0 ? " on" : ""}`} style={mainTab === 0 ? SEL_TAB : undefined} onClick={() => setMainTab(0)}>News</button>
          <button className={`tab${mainTab === 1 ? " on" : ""}`} style={mainTab === 1 ? SEL_TAB : undefined} onClick={() => setMainTab(1)}>Announcement</button>
          <button className={`tab${mainTab === 2 ? " on" : ""}`} style={mainTab === 2 ? SEL_TAB : undefined} onClick={() => setMainTab(2)}>Most Active</button>
          <button className={`tab${mainTab === 3 ? " on" : ""}`} style={mainTab === 3 ? SEL_TAB : undefined} onClick={() => setMainTab(3)}>Biggest %</button>
          <button className={`tab${mainTab === 4 ? " on" : ""}`} style={mainTab === 4 ? SEL_TAB : undefined} onClick={() => setMainTab(4)}>Weekly Summary</button>
          <button className={`tab${mainTab === 5 ? " on" : ""}`} style={mainTab === 5 ? SEL_TAB : undefined} onClick={() => setMainTab(5)}>Monthly Summary</button>
        </div>
      </div>

      {mainTab === 0 && (<>
      {/* Sub-tabs (Live/Premarket/…) + all filters on ONE line. flexWrap is a
          graceful fallback for narrow viewports. Non-sticky so it doesn't stack
          under the sticky primary-tab header above. */}
      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", flexWrap: "wrap", gap: 10, rowGap: 8, padding: "12px 18px", borderBottom: "1px solid var(--border-soft)", position: "relative" }}>
        {/* Search + sector + market-cap, same line as the tabs. Each label and
            its select are one inline-flex unit: as loose siblings in a wrapping
            row they could break apart, leaving "Market cap" stranded on one row
            with its dropdown on the next. */}
        <div style={{ display: "flex", alignItems: "center", gap: 8, flexWrap: "wrap", justifyContent: "flex-end", minWidth: 0 }}>
          {/* nowrap keeps Search / Sector / Market cap on ONE line. The search
              box is the only element allowed to give: basis 190 shrinking to
              110 absorbs the squeeze, so the two dropdowns never drop to a
              second row. */}
          <div style={{ position: "relative", flex: "1 1 190px", minWidth: 110, maxWidth: 320 }}>
            <input
              ref={searchRef}
              className="mv-sel"
              placeholder="Search the feed — ticker, company or keyword…"
              value={search}
              onChange={e => setSearch(e.target.value)}
              autoComplete="off"
              style={{ width: "100%" }}
            />
          </div>
          {search.trim() && (
            <button className="chip ghost" onClick={() => setSearch("")} title="Clear search">Clear</button>
          )}
          {/* View (was the Live / Premarket / After Hours tab row) and Category
              (was the chip row) are dropdowns now, so every filter on this
              screen reads the same way and sits on one line. Counts stay on the
              category options — the number is the reason to pick one. */}
          <span style={{ display: "inline-flex", alignItems: "center", gap: 6, whiteSpace: "nowrap" }}>
            <span style={{ fontSize: ".72rem", color: "var(--text-dim-solid)" }}>View</span>
            <select className="mv-sel" value={activeTab} onChange={e => setActiveTab(Number(e.target.value))}>
              {TABS.map((t, i) => <option key={t} value={i}>{t}</option>)}
            </select>
          </span>
          <span style={{ display: "inline-flex", alignItems: "center", gap: 6, whiteSpace: "nowrap" }}>
            <span style={{ fontSize: ".72rem", color: "var(--text-dim-solid)" }}>Category</span>
            <select className="mv-sel" value={tagFilter} onChange={e => setTagFilter(e.target.value)}>
              <option value="all">All ({tagCounts.all ?? 0})</option>
              {NEWS_TAGS.filter(t => (tagCounts[t.key] ?? 0) > 0).map(t => (
                <option key={t.key} value={t.key}>{t.label} ({tagCounts[t.key] ?? 0})</option>
              ))}
            </select>
          </span>
          <span style={{ display: "inline-flex", alignItems: "center", gap: 6, whiteSpace: "nowrap" }}>
            <span style={{ fontSize: ".72rem", color: "var(--text-dim-solid)" }}>Sector</span>
            <select className="mv-sel" value={effSec} onChange={e => setSecFilter(e.target.value)}>
              {feedSectors.map(s => <option key={s} value={s}>{titleCaseLabel(s)}</option>)}
            </select>
          </span>
          <span style={{ display: "inline-flex", alignItems: "center", gap: 6, whiteSpace: "nowrap" }}>
            <span style={{ fontSize: ".72rem", color: "var(--text-dim-solid)" }}>Market cap</span>
            <select className="mv-sel" value={capFilter} onChange={e => setCapFilter(e.target.value)}>
              {CAP_TIERS.map(c => <option key={c} value={c}>{c}</option>)}
            </select>
          </span>
        </div>
      </div>

      <div style={{ padding: "0 18px 18px" }}>


        <div className="dash">

          {/* Full width: the right rail that used to sit beside this (Before
              the Bell, After the Close, Filings wire, Market regime) is gone,
              so the feed takes all 12 columns instead of 8. Still a flex column
              so the feed card grows to fill the row. */}
          <div className="col-12" style={{ display: "flex", flexDirection: "column", gap: 14 }}>
            {/* Quick lookup — tap a ticker to add it to the feed filter. Sits
                at the TOP of the column; the feed card below flex-fills. */}
            <div className="card" style={{ flexShrink: 0 }}>
              <div className="card-h">
                <div style={{ display: "flex", alignItems: "center", gap: 6 }}><h3>{activeTab === 3 ? "Tracked names" : "Quick filter"}</h3><VendorTag v="polygon" /></div>
              </div>
              <div className="card-b" style={{ paddingTop: 8, display: "flex", gap: 6, flexWrap: "wrap" }}>
                {(activeTab === 3 ? [...mySymbols] : topSymbols).length === 0 ? (
                  <DataState loading={activeTab === 3 ? false : companiesLoading} label={activeTab === 3 ? "No tracked names yet." : "No live companies synced yet."} />
                ) : (activeTab === 3 ? [...mySymbols] : topSymbols).map(sym => (
                  <button
                    key={sym}
                    className={`chip${search.trim().toUpperCase() === sym.toUpperCase() ? " on" : ""}`}
                    onClick={() => setSearch(search.trim().toUpperCase() === sym.toUpperCase() ? "" : sym)}
                  >{sym}</button>
                ))}
              </div>
            </div>

            <div className="card" style={{ flex: 1, minHeight: 0, display: "flex", flexDirection: "column" }}>
              <div className="card-h">
                <div style={{ display: "flex", alignItems: "center", gap: 6, flexWrap: "wrap" }}><h3>{feedLabel.title}{q ? ` · “${search.trim()}”` : ""}</h3><VendorTag v={["polygon", "fmp"]} /></div>
                {feedLabel.badge}
              </div>
              <div className="card-b" style={{ paddingTop: 2, flex: 1, minHeight: 0, overflowY: "auto" }}>
                {feed.length === 0 ? (
                  <DataState loading={liveNewsLoading} label={
                    q
                      ? `No matches for “${search.trim()}” in this tab.`
                      : activeTab === 3
                        ? (uid ? "No live news matches your portfolio or watchlist names right now." : "Sign in and add names to your watchlist or portfolio to see this feed.")
                        : "No live news items in this category right now."} />
                ) : feed.map((item, i) => (
                  <FeedItem
                    key={item.id}
                    item={item}
                    i={i}
                    total={feed.length}
                    onTicker={sym => setSearch(sym)}
                    onAnalysis={setAnalysisTicker}
                    marketCap={companyByTicker.get(item.ticker)?.marketCap ?? null}
                    livePct={feedQuotes.get(item.ticker)?.pctChange ?? companyByTicker.get(item.ticker)?.pctChange ?? null}
                  />
                ))}
              </div>
            </div>
          </div>

        </div>
      </div>
      </>)}

      {mainTab === 1 && <EarningsAnnouncementsTab />}
      {mainTab === 2 && <MostActiveTab />}
      {mainTab === 3 && <BiggestPctTab />}
      {mainTab === 4 && <GlanceTab period="weekly" heading="Weekly summary" />}
      {mainTab === 5 && <GlanceTab period="monthly" heading="Monthly summary" />}

      {analysisTicker && (
        <TickerAnalysisDrawer sym={analysisTicker} onClose={() => setAnalysisTicker(null)} />
      )}
    </>
  );
}
